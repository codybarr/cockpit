import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Only touches the supplied pasteboard. Tests use a uniquely named board, never `.general`.
@MainActor
enum ClipboardPasteboard {
    enum Capture: Sendable {
        case text(String)
        case image(Data)
        case files([URL])
    }

    static let volatileRoots = [
        URL(fileURLWithPath: "/tmp"), URL(fileURLWithPath: "/private/tmp"),
        URL(fileURLWithPath: "/var/folders"), URL(fileURLWithPath: "/private/var/folders"),
        FileManager.default.homeDirectoryForCurrentUser.appending(path: "Library/Caches"),
    ]

    static func read(_ board: NSPasteboard, volatileRoots: [URL]) -> Capture? {
        let ignoredTypes: Set<String> = [
            ClipboardHistory.replayType.rawValue,
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        ]
        guard !(board.types ?? []).contains(where: { ignoredTypes.contains($0.rawValue) }) else { return nil }
        let items = board.pasteboardItems ?? []
        // Bound the batch before decoding. Never turn a partial batch into a successful copy.
        guard items.count <= 100,
              !items.contains(where: { item in item.types.contains { ignoredTypes.contains($0.rawValue) } }) else { return nil }
        let fileItems = items.filter { $0.types.contains(.fileURL) }
        if !fileItems.isEmpty {
            guard fileItems.count == items.count else { return nil }
            var urls: [URL] = []
            for item in fileItems {
                guard let raw = item.string(forType: .fileURL), raw.utf8.count <= 16_384,
                      let url = URL(string: raw), url.isFileURL else { return nil }
                let canonical = url.standardizedFileURL
                if volatileRoots.contains(where: { canonical.path == $0.path || canonical.path.hasPrefix($0.path + "/") }) {
                    // Only a single staged export can fall back to an inline representation.
                    // A mixed batch must never silently become a partial file copy.
                    guard fileItems.count == 1, let inline = inlineContent(on: board) else { return nil }
                    if case let .text(text) = inline, [url.lastPathComponent, url.path, url.absoluteString].contains(text) {
                        return nil
                    }
                    return inline
                }
                urls.append(canonical)
            }
            return .files(urls)
        }
        guard items.count <= 1 else { return nil }
        return inlineContent(on: board)
    }

    private static func inlineContent(on board: NSPasteboard) -> Capture? {
        for type in [NSPasteboard.PasteboardType.png, .tiff] where board.types?.contains(type) == true {
            guard let data = board.data(forType: type), data.count <= ClipboardHistory.entryByteLimit else { return nil }
            return .image(data)
        }
        guard let text = board.string(forType: .string), !text.isEmpty,
              text.utf8.count <= ClipboardHistory.entryByteLimit else { return nil }
        return .text(text)
    }

    static func write(_ entry: ClipboardEntry, plainText: Bool, to board: NSPasteboard) throws {
        let items: [NSPasteboardItem]
        if plainText {
            guard let text = entry.plainText else { throw ClipboardHistory.ClipboardError.unavailable }
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            items = [item]
        } else {
            switch entry.content {
            case let .text(text):
                let item = NSPasteboardItem()
                item.setString(text, forType: .string)
                items = [item]
            case let .image(data, _, _, _):
                let item = NSPasteboardItem()
                item.setData(data, forType: .png)
                items = [item]
            case let .files(urls):
                items = urls.map { url in
                    let item = NSPasteboardItem()
                    item.setString(url.absoluteString, forType: .fileURL)
                    item.setString(url.path, forType: .string)
                    return item
                }
            }
        }
        guard !items.isEmpty else { throw ClipboardHistory.ClipboardError.unavailable }
        for item in items { item.setData(Data(), forType: ClipboardHistory.replayType) }
        board.clearContents()
        guard board.writeObjects(items) else { throw ClipboardHistory.ClipboardError.unavailable }
    }
}

/// Image decoding and conversion never run on the UI actor. Encoded and decoded sizes are bounded.
enum ClipboardContentPreparation {
    static func prepare(_ capture: ClipboardPasteboard.Capture) -> ClipboardEntry? {
        switch capture {
        case let .text(text): return ClipboardEntry(content: .text(text))
        case let .files(urls): return ClipboardEntry(content: .files(urls))
        case let .image(data):
            guard let source = CGImageSourceCreateWithData(data as CFData, nil),
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? Int,
                  let height = properties[kCGImagePropertyPixelHeight] as? Int,
                  width > 0, height > 0, width <= 8_192, height <= 8_192,
                  width * height <= 16_777_216 else { return nil }
            guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: max(width, height),
            ] as CFDictionary),
                  let png = encode(image), png.count <= ClipboardHistory.entryByteLimit,
                  let tile = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceCreateThumbnailWithTransform: true,
                    kCGImageSourceThumbnailMaxPixelSize: 76,
                  ] as CFDictionary), let thumbnail = encode(tile),
                  png.count + thumbnail.count <= ClipboardHistory.entryByteLimit else { return nil }
            return ClipboardEntry(content: .image(png, width: image.width, height: image.height, thumbnail: thumbnail))
        }
    }

    static func validateFiles(in entry: ClipboardEntry) -> Bool {
        guard case let .files(urls) = entry.content else { return true }
        return urls.allSatisfy { $0.isFileURL && FileManager.default.isReadableFile(atPath: $0.path) }
    }

    private static func encode(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image, nil)
        return CGImageDestinationFinalize(destination) ? data as Data : nil
    }
}
